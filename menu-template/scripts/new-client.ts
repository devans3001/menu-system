/**
 * Duplication stub. Dry-run safe by default.
 * Usage: npx tsx scripts/new-client.ts <slug> <intake.json> [--write] [targetFolder]
 * Without --write it only prints what it would do, plus the registry SQL.
 * With --write it writes restaurant.config.ts into the target folder.
 * It never creates GitHub repos, Vercel projects, or database rows itself.
 */
import * as fs from "node:fs";
import * as path from "node:path";

const slug = process.argv[2];
const intakePath = process.argv[3];
const write = process.argv.includes("--write");
const targetArg = process.argv.find(a => a.startsWith("--target="));
const targetFolder = targetArg ? targetArg.split("=")[1] : null;

if (!slug || !intakePath) {
  console.error("Usage: npx tsx scripts/new-client.ts <slug> <intake.json> [--write] [--target=<folder>]");
  process.exit(1);
}
if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) { console.error("Invalid slug: use lowercase kebab-case."); process.exit(1); }

const intake = JSON.parse(fs.readFileSync(intakePath, "utf8"));
const displayName: string = intake.displayName ?? slug;
const configTs = "// Generated by scripts/new-client.ts for " + slug + ". Review the skin pass before deploy.\n" +
  "// Paste these values into the instance restaurant.config.ts (typed in that file).\n" +
  "export const intakeFor_" + slug.replaceAll("-", "_") + " = " + JSON.stringify({ ...intake, slug }, null, 2) + ";\n";

console.log("Dry run:", !write);
console.log("Slug:", slug, "| Display name:", displayName);
console.log("--- Registry row SQL (run in Neon main branch) ---");
console.log(`INSERT INTO restaurants (slug, state, billing_mode) VALUES ('${slug}', 'awaiting_payment', '${intake.billing?.mode ?? "monthly"}') ON CONFLICT (slug) DO NOTHING;`);
console.log(`INSERT INTO menus (slug, menu, version) VALUES ('${slug}', '{}'::jsonb, 1) ON CONFLICT (slug) DO NOTHING;`);
if (write && targetFolder) {
  fs.mkdirSync(targetFolder, { recursive: true });
  fs.writeFileSync(path.join(targetFolder, "restaurant.config.ts"), configTs);
  console.log("Wrote", path.join(targetFolder, "restaurant.config.ts"));
} else {
  console.log("--- restaurant.config.ts preview (not written without --write and --target) ---");
  console.log(configTs.slice(0, 800));
}
